#!/usr/bin/env bash
# Summarise the bug and security review results as Markdown to paste into a PR description.
# Also checks that the reviews cover the current contents with nothing uncommitted.
# Exit codes: 0 = ready to paste / 1 = reviews are stale, failing or missing (reasons are in the output)
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

ROOT="$(repo_root)" || { echo "Not a git repository" >&2; exit 1; }
cd "$ROOT"
BASE="$(resolve_base)" || { echo "No base branch found" >&2; exit 1; }
DIR="$(state_dir)"
HASH="$(diff_hash "$BASE")"

# Prints one of: missing / stale / passed / failed
status_of() {  # $1 = last-result, $2 = last-hash
  if [[ ! -f "$1" ]]; then echo "missing"
  elif [[ "$(cat "$2" 2>/dev/null)" != "$HASH" ]]; then echo "stale"
  elif [[ "$(cut -d' ' -f1 "$1")" == "0" ]]; then echo "passed"
  else echo "failed"
  fi
}
describe() {
  case "$1" in
    missing) echo "Not run" ;;
    stale)   echo "Stale (changes since the last review)" ;;
    passed)  echo "Passed" ;;
    failed)  echo "Failed (open findings)" ;;
  esac
}

BUG_STATE="$(status_of "$DIR/last-result" "$DIR/last-hash")"
SEC_STATE="$(status_of "$DIR/security-last-result" "$DIR/security-last-hash")"

PROBLEMS=()
[[ -n "$(git status --porcelain)" ]] && PROBLEMS+=("There are uncommitted changes. Commit them and run the reviews again")
[[ "$BUG_STATE" != "passed" ]] && PROBLEMS+=("Bug review: $(describe "$BUG_STATE")")
[[ "$SEC_STATE" != "passed" ]] && PROBLEMS+=("Security review: $(describe "$SEC_STATE")")

BUG_FILE="$(cut -d' ' -f2- "$DIR/last-result" 2>/dev/null || true)"
SEC_FILE="$(cut -d' ' -f2- "$DIR/security-last-result" 2>/dev/null || true)"

RISK_LINE="$( [[ -f "$BUG_FILE" ]] && sed -n '2p' "$BUG_FILE" )"
RISK="$(sed -nE 's/^Risk:[[:space:]]*(Low|Medium|High).*/\1/p' <<<"$RISK_LINE")"
RISK_REASON="$(sed -nE 's/^Risk:[[:space:]]*(Low|Medium|High)[[:space:]]*[—-]*[[:space:]]*//p' <<<"$RISK_LINE")"
if [[ -z "$RISK" ]]; then
  RISK="High"; RISK_REASON="Could not read the reviewer's classification, so treating it as High"
fi

BUG_STATUS="$(describe "$BUG_STATE")"
ROUNDS="$(basename "$BUG_FILE" 2>/dev/null | sed -nE 's/round-([0-9]+)\.md/\1/p')"
[[ "$BUG_STATE" == "passed" && -n "$ROUNDS" ]] && BUG_STATUS="Passed (${ROUNDS} round(s))"
SEC_STATUS="$(describe "$SEC_STATE")"
if [[ "$SEC_STATE" == "passed" ]]; then
  LOW="$(head -n 1 "$SEC_FILE" 2>/dev/null | sed -nE 's/.*Low[[:space:]]*([0-9]+).*/\1/p')"
  SEC_STATUS="Passed (no High / Medium)"
  [[ -n "$LOW" && "$LOW" != "0" ]] && SEC_STATUS="Passed (no High / Medium; ${LOW} Low, see details)"
fi

case "$RISK" in
  Low)    FOCUS="Check the review and test results, and confirm no behaviour change slipped in" ;;
  Medium) FOCUS="Read the code as usual, especially whether the tests really exercise the changed behaviour" ;;
  High)   FOCUS="Start from the design. Trace authentication, secrets and external input end to end" ;;
esac

cat <<EOF
<!-- review-loop:start (generated by review-loop's pr-evidence.sh; do not edit by hand) -->
### Independent review

| Item | Result |
|---|---|
| Reviewed commit | \`$(git rev-parse --short HEAD)\` |
| Risk tier | **${RISK}** — ${RISK_REASON} |
| Bug review | ${BUG_STATUS} |
| Security review | ${SEC_STATUS} |

**What to look at (${RISK}):** ${FOCUS}
EOF

if (( ${#PROBLEMS[@]} > 0 )); then
  printf '\n> [!WARNING]\n> These review results do not match the PR contents.\n'
  for p in "${PROBLEMS[@]}"; do printf '> - %s\n' "$p"; done
fi
[[ -f "$BUG_FILE" ]] && printf '\n<details><summary>Bug review details</summary>\n\n%s\n\n</details>\n' "$(cat "$BUG_FILE")"
[[ -f "$SEC_FILE" ]] && printf '\n<details><summary>Security review details</summary>\n\n%s\n\n</details>\n' "$(cat "$SEC_FILE")"
echo "<!-- review-loop:end -->"

(( ${#PROBLEMS[@]} == 0 ))
